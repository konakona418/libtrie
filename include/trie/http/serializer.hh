#pragma once

#include <array>
#include <charconv>
#include <cstddef>
#include <string>
#include <string_view>

#include "trie/http.hh"

namespace trie::http {

constexpr std::string_view reason_phrase(int code) {
  switch (code) {
    case 200: return "OK";
    case 201: return "Created";
    case 202: return "Accepted";
    case 204: return "No Content";
    case 400: return "Bad Request";
    case 401: return "Unauthorized";
    case 404: return "Not Found";
    case 405: return "Method Not Allowed";
    case 409: return "Conflict";
    case 413: return "Payload Too Large";
    case 414: return "URI Too Long";
    case 431: return "Request Header Fields Too Large";
    case 500: return "Internal Server Error";
    case 501: return "Not Implemented";
    case 505: return "HTTP Version Not Supported";
    default: return "Unknown";
  }
}

inline void append_size(std::string& out, std::size_t value) {
  std::array<char, 24> buffer{};
  auto [ptr, ec] = std::to_chars(buffer.data(), buffer.data() + buffer.size(), value);
  if (ec == std::errc{}) out.append(buffer.data(), static_cast<std::size_t>(ptr - buffer.data()));
}

// Serializes a response. Content-Length and Connection are always generated by
// the server; user headers with those names are dropped.
inline std::string serialize_response(response const& res, bool keep_alive, bool head_only) {
  std::string out;
  out.reserve(64 + res.body.size() + res.headers.size() * 32);

  out += "HTTP/1.1 ";
  append_size(out, static_cast<std::size_t>(res.status_code));
  out += ' ';
  out += reason_phrase(res.status_code);
  out += "\r\n";

  for (auto const& header : res.headers) {
    if (iequals(header.first, "content-length") || iequals(header.first, "connection")) continue;
    out += header.first;
    out += ": ";
    out += header.second;
    out += "\r\n";
  }

  out += "Content-Length: ";
  append_size(out, res.body.size());
  out += "\r\n";

  if (!keep_alive) out += "Connection: close\r\n";
  out += "\r\n";

  if (!head_only) out += res.body;
  return out;
}

} // namespace trie::http
